// *****************************************************************************
// Tapir Translator - GenerateMenus: the add-on's menus in the 20 languages
//
//   Usage: GenerateMenus.exe <RFIX/Tapir_TranslatorMenus.grc>
//   Build tool. For each UI language i it writes, from the texts of
//   Src/TT_Texts.cpp, the 5 menus as 'STR#' resources (ids MenuBase (i) + 0..4)
//   and their status-bar help strings (same ids + HelpOffset):
//     +0 input language, +1 output language, +2 Options,
//     +3 online translator, +4 language of the tool itself.
//   ArchiCAD fixes the menus at start-up, so all languages are compiled in and
//   the add-on registers only the menus of the chosen language.
//   Run by the LocalizedMenus target before the resources are compiled; the
//   file is rewritten only when its content changes, so the resources are
//   not recompiled for nothing.
//   Exit codes: 0 success (written or unchanged), 1 write error, 2 wrong arguments.
// *****************************************************************************

#include "TT_Texts.hpp"

#include <cstdio>
#include <string>
#include <vector>

namespace {

// Quotes a text as a GRC string literal. GRC strings have no escape for the
// double quote, so " becomes ' ; a backslash is replaced by / so that no
// escape sequence can appear in the generated string.
std::string String (const std::string& s)
{
	std::string r = "\"";
	for (const char c : s) {
		if (c == '"')
			r += "'";		// no straight double quote inside a GRC string
		else if (c == '\\')
			r += "/";
		else
			r += c;
	}
	return r + "\"";
}

// Appends one menu to the GRC text, as two 'STR#' resources.
//   grc      : GRC text being built
//   id       : resource id of the menu; its help strings use id + HelpOffset
//   title    : resource name (comment only, in French, not shown to the user)
//   subMenu : translated name of the submenu under "Tapir Translator"
//   elements : translated menu items ("-" = separator)
//   helps    : status-bar help of each item, same order as elements
// Step 1: menu resource - "Tapir Translator", the submenu name, then the
//         numbered items (the "[ n ]" comments are the usual GRC layout).
// Step 2: help resource - two empty strings for the two menu levels, then one
//         help string per item.
void Menu (std::string& grc, short id, const char* title, const std::string& subMenu, const std::vector<std::string>& elements,
		   const std::vector<std::string>& helps)
{
	// Step 1
	grc += "'STR#' " + std::to_string (id) + " \"" + title + "\" {\n";
	grc += "/* [   ] */\t\t\"Tapir Translator\"\n";
	grc += "/* [   ] */\t\t" + String (subMenu) + "\n";
	for (size_t i = 0; i < elements.size (); ++i)
		grc += "/* [" + std::to_string (i + 1) + "] */\t\t\t" + String (elements[i]) + "\n";
	grc += "}\n\n";
	// Step 2
	grc += "'STR#' " + std::to_string (id + TT::HelpOffset) + " \"" + title + " (help)\" {\n";
	grc += "/* [   ] */\t\t\"\"\n/* [   ] */\t\t\"\"\n";
	for (size_t i = 0; i < helps.size (); ++i)
		grc += "/* [" + std::to_string (i + 1) + "] */\t\t" + String (helps[i]) + "\n";
	grc += "}\n\n";
}

}	// namespace


// Entry point.
// Step 1: check the argument (path of the .grc file to generate).
// Step 2: build the whole GRC text (UTF-8 with BOM), language by language.
// Step 3: compare with the existing file and write only if it changed.
int main (int argc, char** argv)
{
	// Step 1
	if (argc != 2) {
		std::fprintf (stderr, "usage: GenerateMenus <file.grc>\n");
		return 2;
	}
	// Step 2: header comment of the generated file, then one block per language
	std::string grc = "\xEF\xBB\xBF/* Generated by Tools/GenerateMenus.cpp from Src/TT_Texts.cpp: do not edit by hand. */\n\n";
	for (int l = 0; l < TT::InterfaceLanguageCount; ++l) {
		// T(x): text x in language l
		const auto T = [l] (TT::Text t) { return std::string (TT::Txt (t, l)); };
		const short base = TT::MenuBase (l);
		grc += "/* ===== " + std::string (TT::InterfaceCode (l)) + " ===== */\n\n";

		// Names of the 20 languages (each one written in its own language,
		// as given by TT::InterfaceName), shared by the three language menus
		std::vector<std::string> languages, inputHelps, outputHelps, interfaceHelps;
		for (int i = 0; i < TT::InterfaceLanguageCount; ++i)
			languages.push_back (TT::InterfaceName (i));

		// +0 input language: "Automatic detection" + the 20 languages
		std::vector<std::string> e = { T (TT::M_AUTO) };
		e.insert (e.end (), languages.begin (), languages.end ());
		std::vector<std::string> a (1, T (TT::P_AUTO));
		a.insert (a.end (), languages.size (), T (TT::P_INPUT));
		Menu (grc, base + 0, "Input language", T (TT::M_INPUT), e, a);

		// +1 output language: "No translation" + the 20 languages
		e = { T (TT::M_NONE) };
		e.insert (e.end (), languages.begin (), languages.end ());
		a = { T (TT::P_NONE) };
		a.insert (a.end (), languages.size (), T (TT::P_OUTPUT));
		Menu (grc, base + 1, "Output language", T (TT::M_OUTPUT), e, a);

		// +2 Options: online translation, collection of untranslated texts,
		// separator, open the dictionaries folder, state report
		Menu (grc, base + 2, "Options", T (TT::M_OPTIONS),
			  { T (TT::M_ONLINE), T (TT::M_COLLECT), "-", T (TT::M_FOLDER), T (TT::M_STATUS) },
			  { T (TT::P_ONLINE), T (TT::P_COLLECT), "", T (TT::P_FOLDER), T (TT::P_STATUS) });

		// +3 online translator: the 5 providers (brand names, not translated),
		// separator, keys file, term corrections file
		Menu (grc, base + 3, "Online translator", T (TT::M_TRANSLATOR),
			  { "DeepL", "Microsoft Translator", "Google Cloud Translation", "MyMemory (" + T (TT::M_NO_KEY) + ")", "LibreTranslate",
				"-", T (TT::M_KEYS), T (TT::M_CORRECTIONS) },
			  { T (TT::P_TRANSLATOR), T (TT::P_TRANSLATOR), T (TT::P_TRANSLATOR), T (TT::P_TRANSLATOR), T (TT::P_TRANSLATOR), "",
				T (TT::P_KEYS), T (TT::P_CORRECTIONS) });

		// +4 language of the tool: "Same as ArchiCAD" + the 20 languages
		e = { T (TT::M_INTERFACE_AUTO) };
		e.insert (e.end (), languages.begin (), languages.end ());
		Menu (grc, base + 4, "Tool language", T (TT::M_INTERFACE), e, std::vector<std::string> (e.size (), T (TT::P_INTERFACE)));
	}

	// Step 3: write only if the content changed (avoids a needless recompilation
	// of the resources); the existing file is read in binary mode for an exact compare
	std::string old;
	FILE* f = nullptr;
	if (fopen_s (&f, argv[1], "rb") == 0 && f != nullptr) {
		char buffer[65536];
		size_t n = 0;
		while ((n = std::fread (buffer, 1, sizeof (buffer), f)) > 0)
			old.append (buffer, n);
		std::fclose (f);
	}
	if (old == grc)
		return 0;
	if (fopen_s (&f, argv[1], "wb") != 0 || f == nullptr) {
		std::fprintf (stderr, "GenerateMenus: cannot write %s\n", argv[1]);
		return 1;
	}
	std::fwrite (grc.data (), 1, grc.size (), f);
	std::fclose (f);
	std::printf ("GenerateMenus: %s written (%d languages)\n", argv[1], TT::InterfaceLanguageCount);
	return 0;
}
